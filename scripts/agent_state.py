#!/usr/bin/env python3
"""Local task-state helper for an active coding-agent runner.

This does NOT run coding agents in the background, execute development or mark tests
passed on its own. It safely initializes/reconciles pointers and enforces evidence
before task completion. Canonical state files live in <repo>/.ai/.
"""
import argparse
import datetime as dt
import json
import os
from pathlib import Path
import re
import shutil
import sys
import tempfile

PHASES = ['P0', 'P1', 'P2', 'P3', 'P4']

def timestamp(): return dt.datetime.now(dt.timezone.utc).isoformat(timespec='seconds')
def load(path): return json.loads(path.read_text(encoding='utf-8'))

def atomic_json(path, data):
    path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile('w', dir=path.parent, encoding='utf-8', delete=False) as h:
        json.dump(data, h, ensure_ascii=False, indent=2)
        h.write('\n')
        name=h.name
    os.replace(name, path)

def locate(root):
    ai=root/'.ai'; return ai/'tasks.json', ai/'state.json'

def ensure_initialized(root, companion):
    tp, sp=locate(root)
    ai=root/'.ai'; ai.mkdir(parents=True, exist_ok=True)
    for dest, template in [(tp, companion/'.ai/tasks.template.json'), (sp, companion/'.ai/state.template.json')]:
        if not dest.exists():
            if not template.exists(): raise ValueError(f'Missing initial template: {template}')
            shutil.copyfile(template, dest)
    tasks, state=load(tp), load(sp)
    if tasks.get('schema_version') != 1 or state.get('schema_version') != 1: raise ValueError('Unsupported AI state schema')
    ids=[t['id'] for t in tasks['tasks']]
    if len(ids) != len(set(ids)): raise ValueError('Duplicate task IDs')
    known=set(ids)
    for t in tasks['tasks']:
        if not set(t['dependencies']) <= known: raise ValueError(f'Unknown dependency in {t["id"]}')
    return tp, sp, tasks, state

def ordered(tasks):
    return sorted(tasks['tasks'], key=lambda t:(PHASES.index(t['phase']), t['id'] == t['phase']+'-GATE', t['id']))

def available(tasks):
    done={t['id'] for t in tasks['tasks'] if t['status']=='done'}
    return [t for t in ordered(tasks) if t['status'] in ('pending','failed','in_progress') and all(d in done for d in t['dependencies'])]

def current_task(tasks):
    a=available(tasks)
    return next((t for t in a if t['status']=='in_progress'), a[0] if a else None)

def refresh_state(tasks,state):
    state['task_count']=len(tasks['tasks'])
    state['completed_task_count']=sum(t['status']=='done' for t in tasks['tasks'])
    state['blocked_task_count']=sum(t['status']=='blocked' for t in tasks['tasks'])
    task=current_task(tasks)
    state['next_task']=task['id'] if task else None
    state['current_phase']=task['phase'] if task else next((p for p in PHASES if any(t['phase']==p and t['status']!='done' for t in tasks['tasks'])), 'P4')
    state['last_updated_utc']=timestamp()
    if state.get('status')=='not-started-template': state['status']='initialized'
    for phase in PHASES:
        gate=next((t for t in tasks['tasks'] if t['id']==phase+'-GATE'),None)
        if gate and gate['status']=='done': state['release_gates'][phase]='passed'
    return state

def write_resume(root,tasks,state):
    nexttask=next((t for t in tasks['tasks'] if t['id']==state.get('next_task')),None)
    blocked=[t for t in tasks['tasks'] if t['status']=='blocked']
    lines=['# START_HERE — AI development checkpoint','',
        '> This file was generated by `scripts/agent_state.py` from tracked state. Task evidence is not implied by generated text.','',
        f'Last updated (UTC): {state["last_updated_utc"]}', f'Current phase: **{state["current_phase"]}**',
        f'Active task: `{state.get("active_task") or "None"}`',
        f'Next task: `{state.get("next_task") or "None"}`',
        f'Completed tasks: {state["completed_task_count"]}/{state["task_count"]}',
        f'Blocked tasks: {state["blocked_task_count"]}',
        f'Last verified commit: `{state.get("last_verified_commit") or "None"}`','',
        '## Next executable action','']
    if nexttask:
        lines += [f'- **{nexttask["id"]}: {nexttask["title"]}**',f'- Tier: `{nexttask["tier"]}`; Agent role: `{nexttask["agent"]}`',
                  '- Continue implementation, run tests, record real evidence, then invoke the next-task selection automatically while runner is active.']
    else:
        lines += ['- No unblocked task available. Check whether all gates are verified or dependencies are blocked. Do not spin.']
    lines += ['','## Blockers']
    lines += [f'- `{t["id"]}`: {t.get("last_error") or "missing reason"}' for t in blocked] or ['- None recorded.']
    lines += ['', '## Resume command', '', '```bash', 'python scripts/agent_state.py next', '```',
              '', '## Marketplace/readiness note', '', 'Completion of state tasks requires evidence; actual WordPress/Playground/QIT and marketplace approval are separate facts.','']
    (root/'START_HERE.md').write_text('\n'.join(lines),encoding='utf-8')

def command(args):
    root=Path(args.root).resolve()
    companion=Path(args.companion).resolve() if args.companion else Path(__file__).resolve().parents[1]
    tp, sp, tasks, state=ensure_initialized(root,companion)
    records={t['id']:t for t in tasks['tasks']}
    if args.command in ('start','complete','block'):
        if args.task not in records: raise ValueError(f'Unknown task: {args.task}')
        t=records[args.task]
        if args.command=='start':
            if t['status']=='done': raise ValueError('Already done; never overwrite verified completed task')
            done={x['id'] for x in tasks['tasks'] if x['status']=='done'}
            missing=[d for d in t['dependencies'] if d not in done]
            if missing: raise ValueError(f'Dependencies not finished: {missing}')
            t['status']='in_progress';t['attempts']=t.get('attempts',0)+1;state['active_task']=t['id'];state['status']='in-progress'
        if args.command=='block':
            if not args.reason or len(args.reason.strip())<10: raise ValueError('--reason must explain a genuine blocker')
            t['status']='blocked';t['last_error']=args.reason;state['active_task']=None
        if args.command=='complete':
            if t['status']!='in_progress': raise ValueError('Task must be started before completed')
            if not args.commit or not re.fullmatch('[0-9a-f]{7,40}',args.commit): raise ValueError('Supply actual verified git commit hash via --commit')
            if not args.evidence: raise ValueError('Actual JSON evidence file required')
            ep=Path(args.evidence).resolve()
            if not ep.is_file(): raise ValueError(f'Evidence file missing: {ep}')
            proof=load(ep)
            if proof.get('task_id')!=t['id'] or proof.get('result')!='passed' or not proof.get('command') or not proof.get('environment') or not proof.get('timestamp_utc'):
                raise ValueError('Evidence requires matching task_id, result=passed, command, environment, timestamp_utc')
            asserted=set(proof.get('test_ids',[])); mandatory=set(t.get('test_ids',[]))
            if not mandatory.issubset(asserted): raise ValueError(f'Task tests missing: {sorted(mandatory-asserted)}')
            if not proof.get('assertions_run',False): raise ValueError('Evidence must state assertions_run=true')
            t['status']='done';t['completed_at']=timestamp();t['verified_commit']=args.commit;t['evidence'].append(str(ep));t['last_error']=None
            state['last_verified_commit']=args.commit;state['last_test_run']=str(ep);state['active_task']=None
    state=refresh_state(tasks,state)
    atomic_json(tp,tasks);atomic_json(sp,state);write_resume(root,tasks,state)
    if args.command=='report':
        counts={p: {status: sum(t['phase']==p and t['status']==status for t in tasks['tasks']) for status in ['pending','in_progress','blocked','failed','done']} for p in PHASES}
        print(json.dumps({'next_task':state['next_task'],'phase':state['current_phase'],'counts':counts},indent=2))
    else:
        nexttask=current_task(tasks)
        print(f"{args.command.upper()}: completed={state['completed_task_count']}/{state['task_count']} | phase={state['current_phase']} | next={state['next_task']}")
        if nexttask: print(nexttask['title'])
    return 0

def main():
    ap=argparse.ArgumentParser()
    ap.add_argument('command',choices=['init','next','start','complete','block','report'])
    ap.add_argument('task',nargs='?')
    ap.add_argument('--root',default='.',help='Repository root (contains .ai/)')
    ap.add_argument('--companion',help='Folder containing template .ai/ files')
    ap.add_argument('--evidence',help='Existing structured test evidence file for completion')
    ap.add_argument('--commit',help='Actual verified source commit hash')
    ap.add_argument('--reason',help='Detailed blocker explanation')
    args=ap.parse_args()
    try:
        if args.command in ('start','complete','block') and not args.task: raise ValueError('A task ID is required')
        return command(args)
    except (OSError,ValueError,KeyError,TypeError,json.JSONDecodeError) as e:
        print('AI STATE ERROR:',e,file=sys.stderr)
        return 1

if __name__=='__main__': raise SystemExit(main())
